import { BanglaCharacterDefinition, Stroke } from '../types/font';
import { strokesToNormalizedSvgPath } from './vectorEngine';

export interface SvgExportOptions {
  includeGuides?: boolean;
  color?: string;
  backgroundColor?: 'transparent' | 'white' | '#f8fafc';
  fontName?: string;
  authorName?: string;
}

/**
 * Builds a clean, standalone, standard-compliant SVG string for an individual Bangla character path.
 */
export function buildStandaloneSvgString(
  charDef: BanglaCharacterDefinition,
  svgPath?: string,
  rawStrokes?: Stroke[],
  options: SvgExportOptions = {}
): string {
  const {
    includeGuides = false,
    color = '#111827',
    backgroundColor = 'transparent',
    fontName = 'Bangla Font Craft',
    authorName = 'Bangla Typographer',
  } = options;

  // Determine path data: provided svgPath, or generated from rawStrokes, or fallback to referenceSvgPath
  let pathData = svgPath?.trim() || '';
  if (!pathData && rawStrokes && rawStrokes.length > 0) {
    // If rawStrokes were stored in original canvas dimensions (typically 600x600)
    // Find bounds or fallback to normalized 1000
    pathData = strokesToNormalizedSvgPath(rawStrokes, 600, 600);
  }
  const isFallbackReference = !pathData;
  if (!pathData) {
    pathData = charDef.referenceSvgPath;
  }

  // Detect if path is a closed ribbon polygon (contains Z or z) or an open centerline path
  const isClosedOutline = /[Zz]/.test(pathData);

  const timestamp = new Date().toISOString();
  const matraDescription =
    charDef.matraType === 'full'
      ? 'পূর্ণমাত্রা (Full Matra)'
      : charDef.matraType === 'half'
      ? 'অর্ধমাত্রা (Half Matra)'
      : 'মাত্রাহীন (No Matra)';

  // Build guidelines SVG markup if requested
  const guidelinesMarkup = includeGuides
    ? `
  <!-- Typography Reference Guides -->
  <g id="typography-guides" opacity="0.45" stroke-dasharray="6,6" stroke-width="2">
    <!-- Top Matra / Shirorekha (y = 220) -->
    <line x1="60" y1="220" x2="940" y2="220" stroke="#ef4444" stroke-width="2.5" />
    <text x="70" y="210" font-family="sans-serif" font-size="16" fill="#ef4444">মাত্রা (Shirorekha)</text>

    <!-- Meanline / Waistline (y = 510) -->
    <line x1="60" y1="510" x2="940" y2="510" stroke="#3b82f6" stroke-width="1.5" />
    <text x="70" y="500" font-family="sans-serif" font-size="16" fill="#3b82f6">মধ্যরেখা (Meanline)</text>

    <!-- Baseline (y = 800) -->
    <line x1="60" y1="800" x2="940" y2="800" stroke="#10b981" stroke-width="2" />
    <text x="70" y="790" font-family="sans-serif" font-size="16" fill="#10b981">ভিত্তিরেখা (Baseline)</text>

    <!-- Center Balance Alignment (x = 500) -->
    <line x1="500" y1="80" x2="500" y2="920" stroke="#94a3b8" stroke-width="1" />
  </g>`
    : '';

  // Background rect
  const backgroundMarkup =
    backgroundColor !== 'transparent'
      ? `\n  <rect width="1000" height="1000" fill="${backgroundColor}" />`
      : '';

  // Path element markup
  const pathMarkup = isClosedOutline
    ? `  <path id="char-path-${charDef.id}" d="${pathData}" fill="${color}" stroke="none" fill-rule="nonzero" />`
    : `  <path id="char-path-${charDef.id}" d="${pathData}" fill="none" stroke="${color}" stroke-width="32" stroke-linecap="round" stroke-linejoin="round" />`;

  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg"
     xmlns:xlink="http://www.w3.org/1999/xlink"
     viewBox="0 0 1000 1000"
     width="1000"
     height="1000"
     version="1.1">
  <title>${charDef.char} - ${charDef.nameBn} (${charDef.unicodeHex})</title>
  <desc>
    Bengali Character: ${charDef.char} (${charDef.nameBn} / ${charDef.nameEn})
    Unicode Code Point: ${charDef.unicodeHex} (Dec: ${charDef.unicodeDec})
    Category: ${charDef.category}
    Matra Type: ${matraDescription}
    Example: ${charDef.exampleWordBn} (${charDef.exampleWordEn}) ${charDef.emoji}
    Font: ${fontName}
    Author: ${authorName}
    Type: ${isFallbackReference ? 'Reference Template' : 'Hand-drawn Digital Ink Vector'}
    Exported: ${timestamp}
    Generated by: Bangla Font Craft (বাংলা ফন্ট ক্রাফট)
  </desc>${backgroundMarkup}${guidelinesMarkup}

  <!-- Character Vector Path -->
  <g id="bangla-glyph-${charDef.id}">
  ${pathMarkup}
  </g>
</svg>
`.trim();
}

/**
 * Generates and triggers browser file download for a character's standalone .SVG file.
 */
export function exportCharacterAsSvg(
  charDef: BanglaCharacterDefinition,
  svgPath?: string,
  rawStrokes?: Stroke[],
  options: SvgExportOptions = {}
): { filename: string; svgContent: string } {
  const svgContent = buildStandaloneSvgString(charDef, svgPath, rawStrokes, options);

  // Clean filename: e.g. bangla_ka_0x0995.svg or bangla_shoro_o_0x0985.svg
  const cleanCharName = (charDef.nameEn || 'char')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '_')
    .replace(/_+/g, '_');
  const filename = `bangla_${cleanCharName}_${charDef.unicodeHex}.svg`;

  // Create Blob & trigger anchor download
  const blob = new Blob([svgContent], { type: 'image/svg+xml;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);

  // Revoke object URL after slight delay
  setTimeout(() => URL.revokeObjectURL(url), 1000);

  return { filename, svgContent };
}

/**
 * Copies character SVG XML string to the user clipboard.
 */
export async function copyCharacterSvgToClipboard(
  charDef: BanglaCharacterDefinition,
  svgPath?: string,
  rawStrokes?: Stroke[],
  options: SvgExportOptions = {}
): Promise<boolean> {
  const svgContent = buildStandaloneSvgString(charDef, svgPath, rawStrokes, options);
  try {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      await navigator.clipboard.writeText(svgContent);
      return true;
    }
  } catch (err) {
    console.warn('Clipboard writeText failed, fallback:', err);
  }
  return false;
}
